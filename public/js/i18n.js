// Expressions avec nombres : « 4V 5D », « 59 % », « 103 V · 73 D »…
const RULES = [
  [/(\d)\s?%/g, '$1%'],
  [/(\d+)\s?V(?=\s|$|–|-|·)/g, '$1W'],
  [/(\d+)\s?D(?=\s|$|·)/g, '$1L'],
  [/(\d) k\b/g, '$1k'],
  [/\bniv\. /g, 'lvl '],
  [/(\d+) sur (\d+) sur (\d+)/g, '$1/$2/$3'],
  [/\bsur (?=\d)/g, 'out of '],
  [/\bsur (?=[A-Z])/g, 'on '],
  [/(\d) à (?=\d)/g, '$1–'],
  [/(\d+) p\.,/g, '$1 g.,'],
  [/(\d+) p\.$/g, '$1 g.'],
  [/(\d) po\b/g, '$1 g'],
  [/(\d+)e place\b/g, (m, n) => `${n}${ord(n)} place`],
  [/(\d+)re\b/g, (m, n) => `${n}${ord(n)}`],
  [/\b(\d+)e\b/g, (m, n) => `${n}${ord(n)}`],
];
function ord(n) {
  n = Number(n);
  const s = n % 100;
  if (s >= 11 && s <= 13) return 'th';
  return ['th', 'st', 'nd', 'rd'][n % 10] || 'th';
}

const keys = Object.keys(PHRASES).sort((a, b) => b.length - a.length);
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const RE = new RegExp(`(?<![\\p{L}\\p{N}])(?:${keys.map(esc).join('|')})(?![\\p{L}\\p{N}])`, 'gu');

export function translateText(t) {
  if (!t || !/[A-Za-zÀ-ÿ%\d]/.test(t)) return t;
  let out = t.replace(/[\u00a0\u202f]/g, ' ').replace(RE, (m) => PHRASES[m] ?? m);
  if (out === t.replace(/[\u00a0\u202f]/g, ' ') && !/\d/.test(t)) return t;
  for (const [re, rep] of RULES) out = out.replace(re, rep);
  return out;
}

// Zones jamais traduites : pseudos des joueurs et contenus saisis.
const SKIP = 'script,style,code,[data-nt],.p-name > span,.pl-name a:not(.who),.sb-n > a:not(.who),.lp-name,.omni-main b,.mini-list .nm a,.m-teams a,.lc-head a:not(.who),.sb-n > span:first-child';
const ATTRS = ['title', 'placeholder', 'aria-label'];

function walk(root) {
  if (root.nodeType === 3) return fixText(root);
  if (root.nodeType !== 1 || root.closest?.(SKIP)) return;
  for (const a of ATTRS) fixAttr(root, a);
  const tw = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let n = tw.nextNode();
  while (n) {
    if (n.nodeType === 1) {
      if (n.matches(SKIP)) {
        n = nextSkipping(tw, n);
        continue;
      }
      for (const a of ATTRS) fixAttr(n, a);
    } else fixText(n);
    n = tw.nextNode();
  }
}
function nextSkipping(tw, el) {
  let n = el;
  while (n && !n.nextSibling) n = n.parentNode;
  if (!n) return null;
  tw.currentNode = n.nextSibling;
  return tw.currentNode;
}
// Valeurs déjà traduites : un texte anglais n'est jamais retraduit (« or » anglais ≠ « or » français).
const DONE = new WeakMap();
function fixText(node) {
  const p = node.parentElement;
  if (!p || p.closest(SKIP)) return;
  const v = node.nodeValue;
  if (DONE.get(node) === v) return;
  const t = translateText(v);
  DONE.set(node, t);
  if (t !== v) node.nodeValue = t;
}
function fixAttr(el, a) {
  const v = el.getAttribute(a);
  if (!v) return;
  let m = DONE.get(el);
  if (!m) DONE.set(el, (m = {}));
  if (m[a] === v) return;
  const t = translateText(v);
  m[a] = t;
  if (t !== v) el.setAttribute(a, t);
}

export function startTranslation() {
  document.documentElement.lang = 'en';
  walk(document.body);
  document.title = translateText(document.title);
  const mo = new MutationObserver((list) => {
    mo.disconnect();
    for (const m of list) {
      if (m.type === 'characterData') fixText(m.target);
      else if (m.type === 'attributes') walk(m.target);
      else m.addedNodes.forEach((n) => walk(n));
    }
    if (/[À-ÿ]/.test(document.title)) document.title = translateText(document.title);
    observe();
  });
  const observe = () => mo.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  observe();
}
